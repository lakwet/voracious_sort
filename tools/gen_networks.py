# Usage: python3 tools/gen_networks.py
# Writes src/dedicated/small_networks.rs (included by small_sort.rs): sorting
# networks as straight-line compare-exchanges, one per length 2..=32.
#
# Each network is Batcher's odd-even merge sort for the next power of two,
# pruned: with the extra slots holding the largest key, a compare-exchange
# touching one of them never moves anything, so it is dropped.
import os


def oddeven_merge(lo, n, r):
    step = r * 2
    if step < n:
        yield from oddeven_merge(lo, n, step)
        yield from oddeven_merge(lo + r, n, step)
        for i in range(lo + r, lo + n - r, step):
            yield (i, i + r)
    else:
        yield (lo, lo + r)


def oddeven_merge_sort_range(lo, hi):
    if (hi - lo) >= 1:
        mid = lo + ((hi - lo) // 2)
        yield from oddeven_merge_sort_range(lo, mid)
        yield from oddeven_merge_sort_range(mid + 1, hi)
        yield from oddeven_merge(lo, hi - lo + 1, 1)


def network(n):
    size = 1
    while size < n:
        size *= 2
    return [(i, j) for (i, j) in oddeven_merge_sort_range(0, size - 1) if j < n]


def check(n, pairs):
    # 0-1 principle: a network sorts every input iff it sorts every 0/1 input.
    for mask in range(1 << n):
        a = [(mask >> k) & 1 for k in range(n)]
        for (i, j) in pairs:
            if a[i] > a[j]:
                a[i], a[j] = a[j], a[i]
        assert a == sorted(a), (n, mask)


MAX = 32
out = [
    "// Generated by tools/gen_networks.py: pruned Batcher odd-even merge sort",
    "// networks, one per length. Do not edit by hand.",
    "",
]
counts = {}
for n in range(2, MAX + 1):
    pairs = network(n)
    if n <= 20:
        check(n, pairs)
    counts[n] = len(pairs)
    out.append("/// Sorts %d keys (%d compare-exchanges)." % (n, len(pairs)))
    out.append("#[inline(always)]")
    out.append("fn network%d<K: Copy + Ord>(a: &mut [K; %d]) {" % (n, n))
    for (i, j) in pairs:
        out.append("    cswap(a, %d, %d);" % (i, j))
    out.append("}")
    out.append("")

out.append("/// Sorts `keys` (length 2..=%d) with the network of its length." % MAX)
out.append("#[inline(always)]")
out.append("fn network_any<K: Copy + Ord>(keys: &mut [K]) {")
out.append("    match keys.len() {")
for n in range(2, MAX + 1):
    out.append("        %d => network%d(<&mut [K; %d]>::try_from(keys).unwrap())," % (n, n, n))
out.append("        _ => {}")
out.append("    }")
out.append("}")
out.append("")

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "dedicated", "small_networks.rs")
with open(path, "w", newline="\n") as f:
    f.write("\n".join(out))
print(counts)
